export function generateRandomPlayer(role: PositionRole = 'CMF', forcedNation?: string, customName?: string): Player {
  const nation = forcedNation ? getNationByName(forcedNation) : getRandomNation();
  const hairStyles: ('short-fade' | 'curls' | 'ponytail' | 'topknot' | 'buzz' | 'parted' | 'afro' | 'wavy-headband')[] = [
    'short-fade', 'curls', 'ponytail', 'topknot', 'buzz', 'parted', 'afro', 'wavy-headband'
  ];
  const hairColors = ['#1c1917', '#3d2314', '#78350f', '#f59e0b', '#000000'];
  const skinTones = ['#fed7aa', '#f4caa1', '#e2b389', '#c88c5a', '#9f6b43', '#7c4c28'];
  const facialHairs: ('none' | 'stubble' | 'full-beard' | 'goatee')[] = ['none', 'stubble', 'full-beard', 'goatee'];
  const kitColors = ['#dc2626', '#1d4ed8', '#059669', '#ffffff', '#eab308', '#9333ea', '#38bdf8'];

  // Weighted rating distribution
  const r = Math.random();
  let ovr = 75;
  let cardTier: CardTier = 'silver';
  if (r > 0.95) {
    ovr = Math.floor(Math.random() * 4) + 94; // 94-97
    cardTier = 'goat';
  } else if (r > 0.86) {
    ovr = Math.floor(Math.random() * 4) + 90; // 90-93
    cardTier = 'toty';
  } else if (r > 0.65) {
    ovr = Math.floor(Math.random() * 5) + 85; // 85-89
    cardTier = 'gold';
  } else if (r > 0.35) {
    ovr = Math.floor(Math.random() * 5) + 80; // 80-84
    cardTier = 'emerald';
  } else {
    ovr = Math.floor(Math.random() * 6) + 74; // 74-79
    cardTier = 'silver';
  }

  const isGK = role === 'GK';
  const age = Math.floor(Math.random() * 12) + 19; // 19-31
  const potential = Math.min(99, ovr + Math.max(0, Math.floor(Math.random() * 8) + (27 - age)));

  const playStyles: PlayStyle[] = [
    'Tezkor hujumchi', 'Jarima maydoni ovchisi', 'Ijodkor pleymeyker', 'To‘p qaytaruvchi',
    'Box-to-box', 'Texnik qanot', 'Himoyaviy tayanch', 'Pas ustasi', 'Klassik himoyachi',
    'Darvoza qo‘riqchisi', 'Pressing mutaxassisi', 'Uzoq zarba ustasi'
  ];

  const firstNames = ['Lucas', 'Mateo', 'Enzo', 'Gabriel', 'Julian', 'Marco', 'Davron', 'Javohir', 'Aziz', 'Sardor', 'Karim', 'Hugo', 'Noah', 'Leo', 'Bruno', 'Alejandro', 'Federico', 'Thiago'];
  const lastNames = ['Silva', 'Santos', 'Fernandez', 'Alvarez', 'Moreno', 'Rossi', 'Tursunov', 'Karimov', 'Rahimov', 'Muller', 'Schmidt', 'Diallo', 'Traore', 'Gomez', 'Romero', 'Perez'];
  const generatedName = customName?.trim() || `${firstNames[Math.floor(Math.random() * firstNames.length)]} ${lastNames[Math.floor(Math.random() * lastNames.length)]}`;

  const family: 'GK' | 'DF' | 'MF' | 'FW' = isGK ? 'GK' : ['CB', 'LB', 'RB', 'LWB', 'RWB'].includes(role) ? 'DF' : ['DMF', 'CMF', 'AMF', 'LMF', 'RMF'].includes(role) ? 'MF' : 'FW';

  const attrs = isGK
    ? {
        pac: Math.floor(ovr * 0.55),
        sho: 25,
        pas: Math.floor(ovr * 0.75),
        dri: 45,
        def: Math.floor(ovr * 0.9),
        phy: Math.floor(ovr * 0.85),
        div: Math.min(99, Math.floor(ovr * (0.95 + Math.random() * 0.08))),
        ref: Math.min(99, Math.floor(ovr * (0.96 + Math.random() * 0.08))),
        han: Math.min(99, Math.floor(ovr * (0.94 + Math.random() * 0.08))),
        pos: Math.min(99, Math.floor(ovr * (0.95 + Math.random() * 0.08))),
        kic: Math.min(99, Math.floor(ovr * (0.8 + Math.random() * 0.1))),
        spd: Math.floor(ovr * 0.55)
      }
    : {
        pac: Math.min(99, Math.floor(ovr * (family === 'FW' ? 0.98 : family === 'MF' ? 0.88 : 0.85))),
        sho: Math.min(99, Math.floor(ovr * (family === 'FW' ? 0.97 : family === 'MF' ? 0.85 : 0.55))),
        pas: Math.min(99, Math.floor(ovr * (family === 'MF' ? 0.98 : family === 'FW' ? 0.84 : 0.8))),
        dri: Math.min(99, Math.floor(ovr * (family === 'FW' || family === 'MF' ? 0.96 : 0.72))),
        def: Math.min(99, Math.floor(ovr * (family === 'DF' ? 0.98 : family === 'MF' ? 0.78 : 0.4))),
        phy: Math.min(99, Math.floor(ovr * (family === 'DF' ? 0.94 : 0.86)))
      };

  const getNaturalPositions = (r: PositionRole): PositionRole[] => {
    switch (r) {
      case 'GK': return ['GK'];
      case 'CB': return ['CB', 'LB', 'RB'];
      case 'LB': return ['LB', 'LWB', 'LMF'];
      case 'RB': return ['RB', 'RWB', 'RMF'];
      case 'DMF': return ['DMF', 'CMF', 'CB'];
      case 'CMF': return ['CMF', 'DMF', 'AMF'];
      case 'AMF': return ['AMF', 'CMF', 'SS', 'LWF', 'RWF'];
      case 'LWF': return ['LWF', 'LMF', 'CF', 'SS'];
      case 'RWF': return ['RWF', 'RMF', 'CF', 'SS'];
      case 'CF': case 'ST': return ['CF', 'ST', 'SS', 'LWF'];
      case 'SS': return ['SS', 'CF', 'AMF'];
      case 'LMF': return ['LMF', 'LWF', 'LB'];
      case 'RMF': return ['RMF', 'RWF', 'RB'];
      default: return [r];
    }
  };

  const clubs = [
    'Real Madrid', 'Manchester City', 'FC Barcelona', 'Arsenal', 'Liverpool',
    'Bayern Munich', 'Paris Saint-Germain', 'Inter Milan', 'Bayer Leverkusen', 'Juventus',
    'Atlético Madrid', 'Chelsea', 'Manchester United', 'Borussia Dortmund', 'AC Milan',
    'Napoli', 'Tottenham Hotspur', 'Aston Villa', 'Sporting CP', 'Benfica', 'Ajax',
    'Galatasaray', 'AS Roma', 'Al-Nassr', 'Inter Miami', 'Paxtakor Toshkent', 'Nasaf Qarshi'
  ];
  const chosenClub = clubs[Math.floor(Math.random() * clubs.length)];

  return {
    id: `rand_${Date.now()}_${Math.random().toString(36).substring(2, 8)}`,
    name: generatedName,
    role,
    displayRole: role,
    naturalPositions: getNaturalPositions(role),
    family,
    ovr,
    potential,
    nation,
    club: chosenClub,
    league: 'Jahon Elit Ligasi',
    cardTier,
    attrs,
    avatar: {
      skinTone: skinTones[Math.floor(Math.random() * skinTones.length)],
      hairStyle: hairStyles[Math.floor(Math.random() * hairStyles.length)],
      hairColor: hairColors[Math.floor(Math.random() * hairColors.length)],
      facialHair: facialHairs[Math.floor(Math.random() * facialHairs.length)],
      kitPrimaryColor: kitColors[Math.floor(Math.random() * kitColors.length)],
      kitSecondaryColor: '#ffffff'
    },
    playStyle: playStyles[Math.floor(Math.random() * playStyles.length)],
    skills: ['Through Passing', 'Speed Dribbling', 'First-time Shot'],
    age,
    foot: Math.random() > 0.3 ? 'O‘ng' : 'Chap',
    height: Math.floor(Math.random() * 25) + 172,
    weight: Math.floor(Math.random() * 22) + 68,
    form: Math.floor(Math.random() * 25) + 75,
    condition: Math.floor(Math.random() * 25) + 75,
    marketValue: Math.round(ovr * ovr * 19000),
    level: Math.max(1, age - 17),
    xp: 25
  };
}
